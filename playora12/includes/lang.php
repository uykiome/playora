/**
 * Playora multilingual support (Kazakh / Russian / English).
 * All interface texts live in this file, so every page speaks one language.
 * Usage in templates: <?= e(t('nav.home')) ?>
 */

const SUPPORTED_LANGS = ['kk', 'ru', 'en'];
const DEFAULT_LANG = 'kk';

function current_lang(): string
{
    $lang = $_COOKIE['playora_lang'] ?? DEFAULT_LANG;
    return is_string($lang) && in_array($lang, SUPPORTED_LANGS, true) ? $lang : DEFAULT_LANG;
}

/** Saves the chosen language from ?lang=xx in a cookie and reloads the page without the parameter. */
function handle_language_switch(): void
{
    $requested = $_GET['lang'] ?? null;
    if (!is_string($requested) || !in_array($requested, SUPPORTED_LANGS, true)) {
        return;
    }
    $isHttps = !empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off';
    setcookie('playora_lang', $requested, [
        'expires' => time() + 60 * 60 * 24 * 365,
        'path' => '/',
        'secure' => $isHttps,
        'httponly' => true,
        'samesite' => 'Lax',
    ]);
    $_COOKIE['playora_lang'] = $requested;

    $path = basename((string) parse_url((string) ($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH));
    if ($path === '' || !preg_match('/^[A-Za-z0-9_.-]+\.php$/', $path)) {
        $path = 'index.php';
    }
    $query = $_GET;
    unset($query['lang']);
    header('Location: ' . $path . ($query ? '?' . http_build_query($query) : ''));
    exit;
}

/** Returns a translated string. Placeholders look like {name}. Falls back to Kazakh, then to the key. */
function t(string $key, array $vars = []): string
{
    $all = lang_strings();
    $text = $all[current_lang()][$key] ?? $all[DEFAULT_LANG][$key] ?? $key;
    foreach ($vars as $name => $value) {
        $text = str_replace('{' . $name . '}', (string) $value, $text);
    }
    return $text;
}

function genre_label(string $genre): string
{
    $key = 'genre.' . $genre;
    $label = t($key);
    return $label === $key ? ucfirst($genre) : $label;
}

function game_description(array $game): string
{
    $key = 'desc.' . $game['slug'];
    $text = t($key);
    return $text === $key ? (string) $game['description'] : $text;
}

function game_mode_label(string $mode): string
{
    $map = [
        'Single-player' => 'mode.single',
        'Single-player / Online' => 'mode.single_online',
        'Online' => 'mode.online',
        'Online multiplayer' => 'mode.online_mp',
        'Online co-op' => 'mode.online_coop',
    ];
    return isset($map[$mode]) ? t($map[$mode]) : $mode;
}

function platforms_label(string $platforms): string
{
    $parts = array_map('trim', explode(',', $platforms));
    $parts = array_map(static function (string $part): string {
        $key = 'platform.' . $part;
        $label = t($key);
        return $label === $key ? $part : $label;
    }, $parts);
    return implode(', ', $parts);
}

